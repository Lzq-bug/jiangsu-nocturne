/* ------------------------------------------------------------------ 高程函数
 * 几何、灯具、机位都走这三个函数，任何一处挪了，站的高度与热点跟着挪。
 */

/** 自然地面（含护坡）：水线内给的是河床，略低于水面以免与水面同高打架 */
export function groundY(_x, z) {
  const a = Math.abs(z);
  if (a <= RIVER.waterHalf) return -1.8;
  if (a >= RIVER.beachTo) {
    // 岸地往里侧缓倾，城市地坪略高于堤顶
    const t = Math.min(1, (a - RIVER.beachTo) / 900);
    return RIVER.shoreY + 2.6 * t;
  }
  const t = (a - RIVER.beachFrom) / (RIVER.beachTo - RIVER.beachFrom);
  return 1.2 + (RIVER.shoreY - 1.2) * smooth(t);
}

/** 上层公路铺装顶 */
export function roadY(z) {
  const a = Math.abs(z);
  if (a <= MAIN_END) return GIRDER.roadY;
  const end = a > 788 && z < 0 ? -APPROACH.northEnd : APPROACH.southEnd;
  const t = clamp((a - MAIN_END) / (end - MAIN_END), 0, 1);
  // 桥头一段做竖曲线，坡度约 2.2%，与 1576+3013=4589 的分工自洽
  return lerp(GIRDER.roadY, APPROACH.endY, easeGrade(t));
}

/** 下层铁路道床顶 */
export function railY(z) {
  const a = Math.abs(z);
  if (a <= MAIN_END) return GIRDER.railY;
  const t = clamp((a - MAIN_END) / (APPROACH.railViaductEnd - MAIN_END), 0, 1);
  return lerp(GIRDER.railY, APPROACH.railEndY, easeGrade(t));
}

const easeGrade = (t) => {
  // 前 12% 保持平坡（桥头），之后匀降，末端再抹平
  const s = clamp((t - 0.12) / 0.82, 0, 1);
  return 0.12 * t + 0.88 * smooth(s);
};

const smooth = (t) => t * t * (3 - 2 * t);
const clamp = (v, a, b) => Math.min(b, Math.max(a, v));
const lerp = (a, b, t) => a + (b - a) * t;

