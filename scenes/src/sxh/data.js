/** 湖道中线 x 与半宽：出图与地形共用同一函数，岸线才对得上 */
export function channelAt(z) {
  const cx = 9 * Math.sin(z * 0.0068) - 5 * Math.sin(z * 0.0165);
  let w = 30 + 8 * Math.sin(z * 0.0105 + 0.3);
  // 桥前略收，五亭桥两端才落得进岸土；湖面仍有五十米可视宽
  w -= 4 * Math.exp(-(z * z) / (2 * 44 ** 2));
  // 北端收窄成水巷，二十四桥跨得过去
  w -= 8 * Math.exp(-((z - LAKE.bridge24.z) ** 2) / (2 * 40 ** 2));
  w -= 6 * Math.exp(-((z - LAKE.rainbowBridge.z) ** 2) / (2 * 34 ** 2));
  return { cx, w: Math.max(14, w) };
}

