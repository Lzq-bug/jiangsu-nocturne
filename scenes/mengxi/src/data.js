/** 梦溪中心线 x = f(z)：从北墙外进来，穿过园子，南出 */
export function streamCenter(z) {
  return 24 + 5.4 * Math.sin(z * 0.072 + 0.55) + 2.2 * Math.sin(z * 0.168 + 1.9);
}
/** 溪之半宽：中段松成一口池 */
export function streamHalf(z) {
  let w = 2.5 + 0.65 * Math.sin(z * 0.13 + 1.2);
  w += 6.9 * Math.exp(-((z - 1.5) ** 2) / (2 * 7.4 ** 2));
  return w;
}
/** 负值在水下 */
export function waterSD(x, z) {
  return Math.abs(x - streamCenter(z)) - streamHalf(z);
}
/** 台地与驳岸：离水越近，石壁越低 */
export function groundAt(x, z) {
  const d = waterSD(x, z);
  const t = smoothstep(-1.55, 0.3, d);
  return -0.9 + (GROUND + 0.9) * Math.pow(t, 0.75);
}
export function smoothstep(a, b, v) {
  const t = Math.min(1, Math.max(0, (v - a) / (b - a)));
  return t * t * (3 - 2 * t);
}

