/** 把 FEATURES 的偏移解成世界坐标与地面高 */
export function site(key) {
  const f = typeof key === 'string' ? FEATURES[key] : key;
  const x = TOP.x + f.dx, z = TOP.z + f.dz;
  const y = terrainHeight(x, z);
  const gx = (terrainHeight(x + 8, z) - terrainHeight(x - 8, z)) / 16;
  const gz = (terrainHeight(x, z + 8) - terrainHeight(x, z - 8)) / 16;
  return { x, y, z, rot: f.rot || 0, gx, gz };
}

