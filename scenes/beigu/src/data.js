/* ------------------------------------------------------------------ 高度场 */

export function terrainHeight(x, z) {
  let h = PLAIN;
  for (const p of HUMPS) {
    const v = PLAIN + humpRise(p, x, z);
    if (v > h) h = v;
  }
  // 顶面留一点起伏，但平台内不许大起大落（寺观要落地）
  const rear = HUMPS[0];
  const dr = Math.hypot((x - rear.x) / rear.rx, (z - rear.z) / rear.rz);
  const rough = dr < rear.flat ? 0.34 : 1;
  h += (Math.sin(x * 0.0132 + z * 0.0088) * 1.5 + Math.sin(z * 0.021 - x * 0.0072) * 1.1) * rough;

  // 岸坡：平地贴江一侧被切下去，崖本身不切
  const b = southBank(x);
  const d = z - b;
  if (d < 30) {
    const shore = d >= 0 ? PLAIN * (0.06 + 0.94 * (d / 30)) : Math.max(-9, -3.2 + d * 0.035);
    const target = Math.min(h, shore);
    const cut = Math.min(1, Math.max(0, 1 - (h - PLAIN) / 7));
    h += (target - h) * cut;
  }
  return h;
}

/** 地表陡度（0..1）：崖面显石、缓坡显土 */
export function steepness(x, z) {
  const d = 6;
  const hx = (terrainHeight(x + d, z) - terrainHeight(x - d, z)) / (2 * d);
  const hz = (terrainHeight(x, z + d) - terrainHeight(x, z - d)) / (2 * d);
  return Math.min(1, Math.hypot(hx, hz) / 0.62);
}

