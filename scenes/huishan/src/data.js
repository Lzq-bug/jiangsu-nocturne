  /** 同一函数供 hills.js 铺地形、也供机位与树定高：两边必须一模一样，否则相机掉进山里 */
  hillY(x, z) {
    let y = 0;
    for (const m of HILLS.masses) {
      const r = Math.hypot((x - m.x) / m.rx, (z - m.z) / m.rz);
      if (r >= 1) continue;
      let h = m.h * Math.pow(1 - r * r, 0.78);
      // 脊线与山脚的起伏：写进同一个函数，网格和采样才不会分家
      h *= 1 + 0.07 * Math.sin(x * 0.021 + m.z * 0.01) * Math.cos(z * 0.017 - m.x * 0.01);
      h *= smoothstep(r, 0.55, 1) * 0.62 + 0.38;
      y = Math.max(y, h);
    }
    return y;
  },
