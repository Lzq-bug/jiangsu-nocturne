/** 某点是否落在水里（光柱、池灯、游船都要靠它折进池面） */
export function clampToPond(x, z) {
  for (const p of PONDS) {
    if (x > p.x0 - 1 && x < p.x1 + 1 && z > p.z0 - 1 && z < p.z1 + 1) {
      return [
        THREE.MathUtils.clamp(x, p.x0 + 1.6, p.x1 - 1.6),
        THREE.MathUtils.clamp(z, p.z0 + 1.6, p.z1 - 1.6),
      ];
    }
  }
  return null;
}

