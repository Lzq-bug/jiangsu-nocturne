/** 脊线上任一点 (u: 0..1) 的山头高度与半宽，机位与山体共用同一函数 */
export function hillAt(u) {
  const arch = Math.sin(Math.PI * Math.pow(u, 0.85));
  const bump = 0.5 * Math.sin(Math.PI * u * 2.4 + 0.6);
  const y = HILL.baseY + (HILL.crestY - HILL.baseY) * (0.34 + 0.66 * (arch * 0.82 + bump * 0.3));
  const w = 9.5 * Math.pow(Math.sin(Math.PI * clampUnit(u)), 0.55) + 2.2;
  return { y, w };
}
const clampUnit = (u) => Math.min(0.985, Math.max(0.015, u));

